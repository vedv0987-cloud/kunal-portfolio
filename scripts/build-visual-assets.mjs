#!/usr/bin/env node
// Roadmap §4 "Recommended registry" — regenerates src/data/visual-assets.ts
// from public/images/HANDOFF-ASSET-INVENTORY.csv. Dev-time only; never run
// against the filesystem inside a deployed request.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const CSV_PATH = "public/images/HANDOFF-ASSET-INVENTORY.csv";
const OUT_PATH = "src/data/visual-assets.ts";

// The CSV has Windows line endings — strip \r from every field, not just the
// line split, since a trailing \r on the last column corrupts the emitted
// TS string literal (an unescaped CR inside a quoted string is invalid).
const lines = readFileSync(CSV_PATH, "utf8").trim().split(/\r?\n/).slice(1);
const rows = lines.map((line) => {
  const [assetId, status, path, width, height, disposition] = line.split(",").map((f) => f.replace(/\r/g, "").trim());
  return { assetId, status, path, width, height, disposition };
});

const generated = rows.filter((r) => r.status === "generated");
const skipped = rows.length - generated.length;

// Prefer the web-sized WebP sibling written by scripts/optimize-images.py
// (same aspect ratio, ~10x lighter); fall back to the PNG master.
const webPath = (path) => {
  const webp = path.replace(/\.png$/, ".webp");
  return webp !== path && existsSync(`public/images/${webp}`) ? webp : path;
};

const entries = generated
  .map(
    (r) => `  "${r.assetId}": {
    url: "/images/${webPath(r.path)}",
    width: ${r.width},
    height: ${r.height},
    disposition: "${r.disposition}",
  },`,
  )
  .join("\n");

const out = `// Auto-generated by scripts/build-visual-assets.mjs from
// public/images/HANDOFF-ASSET-INVENTORY.csv — do not hand-edit.
// Only assets with generation_status === "generated" are included — the
// ${skipped} still-pending assets are deliberately absent so a typo'd asset
// id fails to compile instead of silently rendering a broken image.
//
// Regenerate with: node scripts/build-visual-assets.mjs

export type VisualAsset = {
  /** Public URL, e.g. /images/regenerated-assets-2026-09-14/home/hero-montage/hero-montage.png */
  url: string;
  /** Actual generated PNG dimensions (not the reference crop size) — see roadmap §2. */
  width: number;
  height: number;
  /** "available-review-before-use" (ship it) or "needs-review" (listed in qa-redo.json — do not use until corrected). */
  disposition: "available-review-before-use" | "needs-review";
};

export const visualAssets: Record<string, VisualAsset> = {
${entries}
};

/** True for assets flagged in qa-redo.json — known defects, do not use in production yet. */
export function needsReview(assetId: string): boolean {
  return visualAssets[assetId]?.disposition === "needs-review";
}
`;

writeFileSync(OUT_PATH, out);
console.log(`wrote ${generated.length} generated assets to ${OUT_PATH} (${skipped} pending assets skipped)`);
